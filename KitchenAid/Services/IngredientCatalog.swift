import Foundation
import Observation

/// THE SHIPPED CATALOGUE, decoded once and never copied into SwiftData.
///
/// 669 entries exist so that adding something is PICKING, not typing — Brandon is not
/// going to populate a few hundred ingredients by hand, and an app that asks him to is an
/// app he stops opening. That makes the catalogue content, exactly like a recipe: it is a
/// template a `FoodItem` is minted FROM on demand, not a table of rows. Seeding 669
/// `FoodItem`s at launch would give him a pantry full of things he does not own and a
/// migration every time the catalogue grows.
///
/// `ingredients.json` is generated by `scripts/build_catalogue.py`, which fails the build
/// on a name or alias collision. That check is in Python, it runs in a cloud session, and
/// it is the reason this service can be three dictionaries rather than a disambiguation
/// UI — but the collision is still reported here, because a hand-edit of the JSON bypasses
/// the script entirely and the first silent symptom would be the pantry matching whichever
/// entry happened to come first.
@Observable
final class IngredientCatalog {

    /// Keyed by the entry's own `name`, lowercased. `FoodItem.catalogName` is stamped from
    /// this field at mint time, so this is the lookup that reads a template back.
    private(set) var byName: [String: CatalogEntry] = [:]

    /// Keyed by `NameNormalizer.matchKey`, which folds case, diacritics, parenthetical
    /// asides, trailing prep qualifiers and a regular plural. This is the key a recipe line
    /// arrives on.
    private(set) var byMatchKey: [String: CatalogEntry] = [:]

    /// The 123 hand-written aliases plus the regular plural the build script derives for
    /// every row, all on `matchKey`. Separate from `byMatchKey` so that name matches win
    /// over alias matches without the two having to compete inside one dictionary.
    private(set) var byAliasKey: [String: CatalogEntry] = [:]

    private(set) var diagnostics: [ContentDiagnostic] = []

    private var file: CatalogFile = CatalogFile()
    private let bundle: Bundle
    private let resourceName: String

    init(bundle: Bundle = .main, resourceName: String = "ingredients") {
        self.bundle = bundle
        self.resourceName = resourceName
    }

    // MARK: - Loading

    func load() {
        byName = [:]
        byMatchKey = [:]
        byAliasKey = [:]
        file = CatalogFile()
        var found: [ContentDiagnostic] = []
        let fileName = "\(resourceName).json"

        guard let url = bundle.url(forResource: resourceName, withExtension: "json") else {
            // Not a crash and not an empty catalogue pretending to be a full one. Without
            // this the app would silently fall back to typing every ingredient by hand,
            // which is the one outcome the catalogue exists to prevent.
            diagnostics = [ContentDiagnostic(
                kind: .decodeFailed, fileName: fileName,
                detail: "not in the app bundle — the ingredient picker will be empty"
            )]
            return
        }

        do {
            let data = try Data(contentsOf: url)
            file = try JSONDecoder().decode(CatalogFile.self, from: data)
        } catch {
            diagnostics = [ContentDiagnostic(
                kind: .decodeFailed, fileName: fileName,
                detail: "could not be decoded; never hand-edit it, edit build_catalogue.py and regenerate"
            )]
            return
        }

        // File order, not sorted order: the build script's own first-wins rule is the
        // order it emits, so matching it keeps the Swift and the Python agreeing about
        // which entry survives a collision.
        for entry in file.items {
            let nameKey = entry.name.lowercased()
            guard !nameKey.isEmpty else { continue }

            if let existing = byName[nameKey] {
                found.append(ContentDiagnostic(
                    kind: .duplicateID, fileName: fileName,
                    detail: "\"\(entry.name)\" appears twice (\(existing.aisle) and \(entry.aisle)); the first is used"
                ))
                continue
            }
            byName[nameKey] = entry

            let key = entry.matchKey
            if !key.isEmpty, byMatchKey[key] == nil {
                byMatchKey[key] = entry
            } else if !key.isEmpty, let existing = byMatchKey[key], existing.name != entry.name {
                found.append(ContentDiagnostic(
                    kind: .duplicateID, fileName: fileName,
                    detail: "\"\(entry.name)\" and \"\(existing.name)\" normalize to the same name \"\(key)\""
                ))
            }
        }

        // Aliases in a second pass, so an alias can never shadow a canonical name — which
        // it would if the two were indexed together and the alias happened to be read
        // first. `coriander` is the live example the build script already caught: it is the
        // herb in British usage and the dried seed in American, so only `fresh coriander`
        // is an alias of cilantro.
        for entry in file.items {
            for alias in entry.aliasMatchKeys {
                guard !alias.isEmpty, byMatchKey[alias] == nil else { continue }
                if let existing = byAliasKey[alias], existing.name != entry.name {
                    found.append(ContentDiagnostic(
                        kind: .duplicateID, fileName: fileName,
                        detail: "alias \"\(alias)\" is claimed by both \(existing.name) and \(entry.name); the first is used"
                    ))
                    continue
                }
                byAliasKey[alias] = entry
            }
        }

        // An item in an aisle the walk order does not name would be sorted to the end of
        // the shopping list with nothing saying why, so it is reported rather than
        // silently filed under "Unsorted".
        let order = Set(file.aisleOrder)
        for aisle in aisleNames where !order.contains(aisle) {
            found.append(ContentDiagnostic(
                kind: .unknownAisle, fileName: fileName,
                detail: "aisle \"\(aisle)\" is used by an item but is not in aisleOrder"
            ))
        }

        diagnostics = found
    }

    // MARK: - Lookup

    /// Exact entry by its canonical name, case-insensitively.
    func entry(named name: String) -> CatalogEntry? {
        let key = name.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !key.isEmpty else { return nil }
        return byName[key]
    }

    /// NAME FIRST, THEN ALIAS, both on `matchKey`, so "Green Onions" finds `scallion` and
    /// "Butter, softened" finds `butter`.
    ///
    /// The order matters and is not arbitrary: if an alias could win over a canonical name
    /// then one row's plural could capture another row's actual name, and the pantry would
    /// match the wrong purchase with nothing on screen to show it had.
    func entry(matching raw: String) -> CatalogEntry? {
        if let exact = entry(named: raw) { return exact }
        let key = NameNormalizer.matchKey(raw)
        guard !key.isEmpty else { return nil }
        return byMatchKey[key] ?? byAliasKey[key]
    }

    /// What a recipe line resolves against: `catalogName` when the importer recorded one,
    /// the display name otherwise. `IngredientLine.matchKey` already applies that
    /// preference, so this is the one call a shopping-list builder needs.
    func entry(forLine line: IngredientLine) -> CatalogEntry? {
        if !line.catalogName.isEmpty, let named = entry(named: line.catalogName) { return named }
        let key = line.matchKey
        guard !key.isEmpty else { return nil }
        return byMatchKey[key] ?? byAliasKey[key]
    }

    var all: [CatalogEntry] {
        file.items.sorted { $0.name.localizedStandardCompare($1.name) == .orderedAscending }
    }

    var isEmpty: Bool { byName.isEmpty }

    func entries(inAisle aisle: String) -> [CatalogEntry] {
        all.filter { $0.aisle == aisle }
    }

    /// Everything tracked present-or-absent with no quantity. Counting teaspoons of salt
    /// is work nobody does, and a list that keeps asking for salt is a list you stop
    /// reading.
    var staples: [CatalogEntry] { all.filter { $0.staple } }

    // MARK: - The walk order

    /// THE WALK ORDER, read straight from the JSON. The way you walk a store.
    ///
    /// This key exists in the emitted file precisely because the spec had hand-copied the
    /// order into prose and the two could drift with no test in this repo able to catch it.
    /// `build_catalogue.py` owns the list, validates that it names every aisle and invents
    /// none, and emits it. Nothing here and nothing in the seed keeps a second copy.
    var aisleOrder: [String] { file.aisleOrder }

    /// Every distinct `aisle` actually PRESENT in `items`, in walk order, with anything the
    /// walk order does not name appended alphabetically so it is still reachable.
    ///
    /// A different question from `aisleOrder` and that is why both exist: the walk order is
    /// the store, this is the catalogue. The seed cross-checks `StoreSection` names against
    /// this one.
    var aisleNames: [String] {
        let present = Set(file.items.map { $0.aisle }).filter { !$0.isEmpty }
        let ordered = file.aisleOrder.filter { present.contains($0) }
        let strays = present.subtracting(ordered).sorted()
        return ordered + strays
    }

    /// Index into the walk order, with anything unnamed sorting to the end rather than to
    /// the front — an unknown aisle belongs after the aisles he actually walks, not before
    /// Produce.
    func walkIndex(ofAisle aisle: String) -> Int {
        file.walkIndex(ofAisle: aisle)
    }

    func walkIndex(ofEntry entry: CatalogEntry) -> Int {
        file.walkIndex(ofAisle: entry.aisle)
    }

    var version: Int { file.version }

    var hasDiagnostics: Bool { !diagnostics.isEmpty }
}
