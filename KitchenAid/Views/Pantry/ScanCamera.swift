/// The camera, for the two things he asked to scan: a receipt's text and a barcode's digits.
///
/// ## Why `DataScannerViewController` and not an `AVCaptureSession`
///
/// The alternative was a capture session plus `VNRecognizeTextRequest` on each frame, and the
/// deciding argument is not that it is more code — it is that it is more code **holding
/// pixels**. Rolling it by hand means a `CMSampleBuffer` arriving on a delegate queue, a
/// `CVPixelBuffer` handed to Vision, and a frame buffer this file would own and have to be
/// trusted not to keep. `DataScannerViewController` hands back `RecognizedItem` values —
/// a `transcript` and a barcode `payloadStringValue`, strings both — and never gives this app
/// a frame at all. **Photos are declined everywhere in this app (`CLAUDE.md`), and a receipt
/// is a photograph of his bank balance**, so the component that makes an image impossible to
/// keep wins over the one that merely makes it avoidable.
///
/// It also does live text and barcodes in one component, which is why one representable serves
/// both flows rather than two camera stacks with two sets of permission handling.
///
/// iOS 16 is its floor and this app's is 17 (`CLAUDE.md`), so nothing here needs an
/// `@available` gate. Hardware is a different question, answered by `ScanReadiness` below:
/// `isSupported` is false on plenty of devices and on the simulator, and a black rectangle is
/// worse than a sentence saying the device cannot do this.
///
/// ## No image is ever stored. This is where that is enforced
///
/// Three things, all deliberate, and this is the file to check if the rule ever looks broken:
///
/// 1. Nothing in this type, its coordinator, or either flow that owns it has a `UIImage`, a
///    `Data` or a file path. The callbacks out are `String`s and a `Double`.
/// 2. `DataScannerViewController.capturePhoto()` **exists and is never called.** That is the
///    one API on this component that would produce an image, and leaving it alone is the whole
///    of what this file has to do to keep the rule.
/// 3. No `PhotosUI`, no `PHPickerViewController`, no photo-library permission. The Info.plist
///    generated by `scripts/make_xcodeproj.py` carries `NSCameraUsageDescription` and no photo
///    key, so there is nothing to ask for and nothing to write to.
///
/// A frame is read for its text or its symbol and discarded by VisionKit before this file sees
/// anything. The schema cannot hold one either — see the same note on `FoodItemBarcode`.
struct ScanCamera: UIViewControllerRepresentable {

    /// What this camera is looking for. The receipt flow wants many text blocks at once; a
    /// barcode flow wants one number at a time, which is also what stops a shelf of tins from
    /// arriving as twelve rows he did not ask for.
    let subject: ScanSubject

    /// Driven by the owner so the camera stops the moment the review list appears. A camera
    /// left running is a battery complaint he would never attribute to this screen.
    let isScanning: Bool

    /// `(item id, transcript, vertical position)`. The id is VisionKit's own tracking id, so a
    /// block of text whose reading sharpens as he holds the phone steadier REPLACES its
    /// earlier reading instead of adding a second line. The position is what puts the lines
    /// back in printed order: the recognizer reports what it sees when it sees it, and a
    /// receipt read bottom-up is a receipt he cannot check against the paper in his hand.
    var onText: (UUID, String, Double) -> Void = { _, _, _ in }

    /// `(digits, symbology)`. The digits are the payload exactly as read; normalizing them is
    /// `FoodItemBarcode.normalize(_:)`'s job and nothing here second-guesses it. The symbology
    /// is provenance only — nothing branches on it.
    var onBarcode: (String, String) -> Void = { _, _ in }

    /// The camera became unusable after it had started: another app took it, or the scanner
    /// reported it cannot run here after all. Said out loud rather than left as a frozen
    /// preview.
    var onTrouble: (String) -> Void = { _ in }

    func makeCoordinator() -> Coordinator {
        Coordinator(owner: self)
    }

    func makeUIViewController(context: Context) -> DataScannerViewController {
        let controller = DataScannerViewController(
            recognizedDataTypes: recognizedTypes,
            // Accurate for a receipt, where the whole job is reading small smudged type;
            // balanced for a barcode, where the answer is right or it is nothing.
            qualityLevel: subject == .receiptText ? .accurate : .balanced,
            recognizesMultipleItems: subject == .receiptText,
            // A receipt and a tin both sit still. High frame rate tracking is for a moving
            // target and costs battery for nothing here.
            isHighFrameRateTrackingEnabled: false,
            isPinchToZoomEnabled: true,
            isGuidanceEnabled: true,
            isHighlightingEnabled: true
        )
        controller.delegate = context.coordinator
        return controller
    }

    func updateUIViewController(_ controller: DataScannerViewController, context: Context) {
        // The coordinator holds a COPY of this struct, which SwiftUI rebuilds on every state
        // change. Without this line the callbacks it calls are the ones captured when the
        // camera was created, and a closure capturing a stale `@State` writes into a value
        // nobody is reading any more.
        context.coordinator.owner = self

        if isScanning {
            if !controller.isScanning {
                // `try?` and not a `catch` that reports: this runs inside SwiftUI's update
                // pass, and writing state from there is the "Modifying state during view
                // update" warning, which would make a one-off camera failure into a
                // guaranteed glitch. A real failure arrives through
                // `becameUnavailableWithError` below, asynchronously, where it can be shown.
                try? controller.startScanning()
            }
        } else if controller.isScanning {
            controller.stopScanning()
        }
    }

    /// The camera goes off when the view goes away, and this is the backstop rather than the
    /// plan: both flows also drop `isScanning` as they leave. This catches the case neither of
    /// them can -- the whole navigation stack being torn down under them.
    static func dismantleUIViewController(
        _ controller: DataScannerViewController, coordinator: Coordinator
    ) {
        controller.stopScanning()
    }

    private var recognizedTypes: Set<DataScannerViewController.RecognizedDataType> {
        switch subject {
        case .receiptText:
            return [.text()]
        case .barcode:
            // Every symbology the device supports, which is the honest default: the number is
            // normalized to a GTIN-14 afterwards and a length that is not 8, 12, 13 or 14 is
            // refused there (`FoodItemBarcode.normalize`). Listing symbologies here would be a
            // second place to keep that judgement.
            return [.barcode()]
        }
    }

    /// VisionKit's delegate, which is where a frame has already become a string.
    ///
    /// A class, because `DataScannerViewControllerDelegate` needs a reference type, and the
    /// one piece of mutable state it has is `owner` -- refreshed on every SwiftUI update
    /// above.
    final class Coordinator: NSObject, DataScannerViewControllerDelegate {
        var owner: ScanCamera

        init(owner: ScanCamera) {
            self.owner = owner
            super.init()
        }

        func dataScanner(
            _ dataScanner: DataScannerViewController,
            didAdd addedItems: [RecognizedItem],
            allItems: [RecognizedItem]
        ) {
            for item in addedItems { report(item) }
        }

        func dataScanner(
            _ dataScanner: DataScannerViewController,
            didUpdate updatedItems: [RecognizedItem],
            allItems: [RecognizedItem]
        ) {
            // Text only, and the asymmetry is deliberate. A text block's transcript genuinely
            // improves as the phone steadies, and the id makes that an update rather than a
            // duplicate. A barcode's payload does not improve -- it is a number or it is
            // nothing -- so reporting updates would hand the same tin to the screen a hundred
            // times a second and ask it to decide which were separate packages.
            guard owner.subject == .receiptText else { return }
            for item in updatedItems { report(item) }
        }

        func dataScanner(
            _ dataScanner: DataScannerViewController,
            becameUnavailableWithError error: DataScannerViewController.ScanningUnavailable
        ) {
            owner.onTrouble(error.localizedDescription)
        }

        /// The one place a recognized item becomes something this app keeps, and what it keeps
        /// is a string. **There is no branch here that can reach a frame**: `RecognizedItem`
        /// carries a transcript and a payload, and this switch covers both of them.
        private func report(_ item: RecognizedItem) {
            switch item {
            case .text(let text):
                owner.onText(item.id, text.transcript, Double(item.bounds.topLeft.y))
            case .barcode(let barcode):
                // A symbol with no payload is a read the scanner could not finish. Dropped
                // rather than reported as an empty number, which would become an unreadable
                // row on screen for something that is not a failure he can act on.
                guard let payload = barcode.payloadStringValue, !payload.isEmpty else { return }
                owner.onBarcode(payload, barcode.observation.symbology.rawValue)
            @unknown default:
                // VisionKit gains item kinds with iOS releases. Ignoring one is right: this
                // app wants text and barcodes, and anything else is not a thing it asked for.
                break
            }
        }
    }
}

/// What a scan is looking for.
enum ScanSubject: Equatable {
    case receiptText
    case barcode
}

/// One block of text the recognizer is tracking, as the screen holds it.
///
/// `id` is VisionKit's tracking id, so a re-read of the same block replaces it.
/// `verticalPosition` is the top edge of its bounds in the view, which is only ever used to
/// sort -- its units do not matter and nothing does arithmetic with it.
struct ScannedLine: Identifiable, Hashable {
    let id: UUID
    var text: String
    var verticalPosition: Double
}

/// Whether this device can scan right now, and if not, which sentence to say.
///
/// Four of these five are failures, and each one wants different words and a different next
/// step: `.denied` needs a route to Settings because the app cannot ask twice, `.undecided`
/// needs the ask itself, `.unsupportedDevice` needs the truth rather than a black rectangle,
/// and `.cameraBusy` needs "try again" rather than any of the above. `EmptyStateView`'s
/// `.nothingYet` / `.somethingWrong` split carries the same distinction one level up: the
/// device not having the hardware is not a fault to fix.
enum ScanReadiness: Equatable {
    case ready
    /// `DataScannerViewController.isSupported` is false: no Neural Engine, or the simulator.
    case unsupportedDevice
    /// Supported and permitted, but not available this second -- another app has the camera.
    case cameraBusy
    /// Camera permission has never been asked for.
    case undecided
    case denied
    /// Denied by Screen Time or an MDM profile, which he cannot change from Settings himself.
    case restricted

    /// The order matters. Permission is read BEFORE `isAvailable`, because `isAvailable` is
    /// also false when permission was refused -- reading it first would tell him the camera
    /// was busy when the real answer is that this app is not allowed to use it, and send him
    /// to close other apps instead of to Settings.
    static func probe() -> ScanReadiness {
        guard DataScannerViewController.isSupported else { return .unsupportedDevice }
        switch AVCaptureDevice.authorizationStatus(for: .video) {
        case .notDetermined:
            return .undecided
        case .denied:
            return .denied
        case .restricted:
            return .restricted
        case .authorized:
            break
        @unknown default:
            // A status this build does not know about is treated as "not allowed", which is
            // the safe direction: it shows the Settings route rather than a dead preview.
            return .denied
        }
        guard DataScannerViewController.isAvailable else { return .cameraBusy }
        return .ready
    }
}

// MARK: - The answer both flows are asking for

/// What a scanned line or a scanned number turned out to be, once he has said -- or once the
/// catalogue was clear enough not to ask.
///
/// A `FoodItem` means a row that already exists; a `CatalogEntry` means a template that becomes
/// one through `FoodItemResolver`, the only thing in this app allowed to create a `FoodItem`.
/// The split is not cosmetic: on the receipt list, minting on tap would leave a bare row behind
/// every line he changed his mind about.
///
/// Shared by both flows, which is why it lives here rather than in either one. A receipt line
/// and a barcode ask the same question and take the same four answers; `.skipped` is "leave
/// this line alone" on a receipt and "not now" on a number.
enum ScanAnswer {
    case unanswered
    case item(FoodItem)
    case entry(CatalogEntry)
    case skipped

    var name: String? {
        switch self {
        case .item(let item): return item.displayName
        case .entry(let entry): return entry.name
        case .unanswered, .skipped: return nil
        }
    }

    var isSkipped: Bool {
        if case .skipped = self { return true }
        return false
    }

    var isStaple: Bool {
        switch self {
        case .item(let item): return item.isStaple
        case .entry(let entry): return entry.staple
        case .unanswered, .skipped: return false
        }
    }

    /// Which dimension the printed size should be read in. Weight for cheese, volume for milk,
    /// count for eggs -- the ambiguity `UnitCatalog` already exists to settle.
    var dimension: MeasureDimension? {
        switch self {
        case .item(let item): return item.preferredDimension
        case .entry(let entry): return entry.dimension
        case .unanswered, .skipped: return nil
        }
    }

    /// The unit this food is BOUGHT in, which lives on the catalogue entry and not on the row.
    /// `FoodItemResolver` deliberately does not copy it onto a `FoodItem` -- its own comment
    /// says an add-stock sheet reads it live -- so this reads it live too, the same way
    /// `AddStockSheet` does.
    func purchaseUnit(catalog: IngredientCatalog) -> KitchenUnit? {
        switch self {
        case .item(let item):
            return catalog.entry(named: item.catalogName)?.defaultUnit
        case .entry(let entry):
            return entry.defaultUnit
        case .unanswered, .skipped:
            return nil
        }
    }
}
